// Новые статьи блога по семантическому ядру (docs/seo/blog-semantic-core.csv).
function migration_blog_2026_10(array $db): array
{
    $posts = require APP_DIR . '/content/blog-2026-10.php';
    $ids = array_column($db['posts'], 'id');
    foreach ($posts as $post) {
        if (!in_array($post['id'], $ids, true)) $db['posts'][] = $post;
    }
    return $db;
}
