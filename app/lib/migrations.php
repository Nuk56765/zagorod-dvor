// Разовые обновления данных на хостинге. Каждая миграция выполняется один раз,
// номер последней выполненной хранится в data/db.json (поле phpMigration).
// Правки, которые владелец сделал в админке, миграции не трогают — меняют только старые шаблонные тексты.

function migrations(): array
{
    return [
        1 => 'migration_contacts_murom',
        2 => 'migration_blog_2026_10',
    ];
}

function migrations_pending(array $data): bool
{
    return (int) ($data['phpMigration'] ?? 0) < max(array_keys(migrations()));
}

function run_migrations(array $data): array
{
    foreach (migrations() as $number => $fn) {
        if ((int) ($data['phpMigration'] ?? 0) >= $number) continue;
        $data = $fn($data);
        $data['phpMigration'] = $number;
    }
    return $data;
}

